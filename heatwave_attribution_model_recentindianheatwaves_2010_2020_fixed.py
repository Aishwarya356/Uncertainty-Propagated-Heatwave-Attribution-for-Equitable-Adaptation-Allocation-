def build_X(days, Gv, with_pc=False, poly=False):
    n = len(days); g = np.repeat(Gv, L)
    cols = [np.repeat(S1[days], L), np.repeat(C1[days], L), g, g * np.repeat(SW_S[days], L), np.tile(LOC.lat.values, n), np.tile(LOC.lon.values, n),
            NORM_S[days].ravel(), MARGIN_S[days].ravel()]
    if with_pc: cols += [np.repeat(PCS[days][:, k], L) for k in range(10)]
    if poly:   # nonlinear terms so the logistic baseline can represent a Gaussian-tail exceedance probability
        mg, gsw_ = cols[7], cols[3]; cols += [mg ** 2, mg * g, mg * gsw_, g ** 2]
    return np.column_stack(cols)
class ConstProb:
    # stand-in when the training rows contain only one class (a classifier cannot be fitted then)
    def __init__(self, p): self.p = p
    def predict_proba(self, X): return np.column_stack([1 - np.full(len(X), self.p), np.full(len(X), self.p)])
def fit_base(kind, days, loc_mask=None, seed=0):
    X = build_X(days, G_S[days], kind == "hgb", kind == "lr"); y = HW_S[days].ravel()
    if loc_mask is not None: keep = np.tile(loc_mask, len(days)); X, y = X[keep], y[keep]
    if len(np.unique(y)) < 2: return ConstProb(float(y.mean()) if len(y) else 0.0)
    if kind == "lr": return make_pipeline(StandardScaler(), LogisticRegression(C=1.0, max_iter=300)).fit(X, y)
    return HistGradientBoostingClassifier(max_iter=80, learning_rate=0.08, max_depth=4, min_samples_leaf=40, l2_regularization=1.0, random_state=seed).fit(X, y)
def pred_base(model, kind, days, Gv): return model.predict_proba(build_X(days, Gv, kind == "hgb", kind == "lr"))[:, 1].reshape(len(days), L)
def clim_table(days, loc_mask=None):
    tab = np.array([HW_S[days][MON_S[days] == m].mean(0) for m in SEASON])
    if loc_mask is not None: tab[:, ~loc_mask] = tab[:, loc_mask].mean(1, keepdims=True)
    return tab
