def quantile_map(era, obs, cal):
    if cal.sum() < 100:      # too few paired days for quantile mapping: fall back to a mean-bias correction
        return era + (np.nanmean(obs[cal]) - np.nanmean(era[cal]) if cal.sum() > 0 else 0.0)
    qs = np.linspace(0.01, 0.99, 99)
    eq, oq = np.quantile(era[cal], qs), np.quantile(obs[cal], qs)
    out = np.interp(era, eq, oq)
    lo, hi = era < eq[0], era > eq[-1]
    out[lo] = era[lo] + (oq[0] - eq[0]); out[hi] = era[hi] + (oq[-1] - eq[-1])
    return out
