"""## Step 5 (continued): Uncertainty: a distribution of attribution probabilities per locality-event

For every event we compute FAR under **every combination** of
* **CNN ensemble member** (year-block bootstrap of the training years plus a new random initialisation; its own out-of-bag residual sigma),
* **CMIP6 model** (each with a different human-attributable warming `dG_m`).

That gives `M x (number of models)` samples of P1, P0, FAR, PR and the attributable warming per event. The same procedure is applied to both baselines so that all three methods are comparable. Outputs report the full sample set, not only a mean.
"""

