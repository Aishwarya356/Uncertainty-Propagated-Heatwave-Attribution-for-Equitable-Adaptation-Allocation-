"""## Step 3: Baseline models (the reference to beat)

Two baselines estimate the probability that a given locality-day is a heatwave day under the observed climate, using **only** a GMST covariate, seasonality and locality descriptors. Attribution comes from swapping the GMST covariate for its counterfactual value.

* **B1: Logistic regression** (statistical, non-stationary covariate approach). Features: annual harmonics, GMST, GMST x season, lat, lon, normal, heatwave margin, plus margin-squared, margin x GMST, margin x GMST x season and GMST-squared terms.
* **B2: Gradient boosting** (ML). Same features plus the first 10 principal components of the Z500 anomaly maps, so it *can* see circulation, but only through a generic tabular model with no spatial structure.

A **climatology** forecast (per-locality, per-month heatwave frequency in the training years) is the reference for Brier skill scores.
"""

