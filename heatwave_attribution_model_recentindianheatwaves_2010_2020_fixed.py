def _download(url, path, timeout=180):
    path = Path(path)
    if path.exists() and path.stat().st_size > 0:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    r = requests.get(url, timeout=timeout, stream=True)
    r.raise_for_status()
    tmp = path.with_suffix(path.suffix + ".part")
    with open(tmp, "wb") as f:
        for chunk in r.iter_content(1024 * 1024):
            if chunk: f.write(chunk)
    if tmp.stat().st_size == 0:
        tmp.unlink(missing_ok=True)
        raise RuntimeError(f"Empty download: {url}")
    tmp.replace(path)
    return path

def _open_remote_dataset(url, attempts=5, delay=4):
    """Open a remote NetCDF with retries for intermittent NOAA THREDDS failures."""
    last = None
    for attempt in range(1, attempts + 1):
        try:
            # Explicit backend is more predictable for THREDDS OPeNDAP URLs.
            return xr.open_dataset(url, engine="netcdf4", decode_times=True)
        except Exception as exc:
            last = exc
            _log(f"Remote open retry {attempt}/{attempts} for {url.rsplit('/', 1)[-1]}: {type(exc).__name__}: {str(exc)[:100]}")
            if attempt < attempts:
                time.sleep(delay * attempt)
    raise RuntimeError(f"Could not open remote NetCDF after {attempts} attempts: {url}; last error: {last}")

