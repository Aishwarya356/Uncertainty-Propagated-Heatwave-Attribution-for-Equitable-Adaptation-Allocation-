"""## Step 4: Attribution model: CNN + partial dependence

Following Trok et al. (2024), a **CNN** learns the daily temperature anomaly from (i) the Z500 circulation map, (ii) the global-mean temperature `G`, (iii) the season and (iv) locality descriptors (lat, lon, peak normal).
This lets the model be evaluated on **held-out localities**.

* **Factual:** feed observed circulation and observed `G(y)`.
* **Counterfactual:** keep the *same* circulation but replace `G` by the CMIP6-derived `G_cf,m(y) = G_obs - dG_m`. The change in the predicted temperature is the attributable warming.
* **Partial dependence:** averaging the prediction over the observed circulation distribution while sweeping `G` yields the response curve.
* **Probabilities:** predictive distribution = CNN mean + Gaussian residual with `sigma` estimated on *out-of-bag* years. For an event day with margin `m` above normal:
  `P1 = P(anomaly >= m | circulation, G_obs)`, `P0 = P(anomaly >= m | circulation, G_cf)`, **FAR = 1 - P0/P1** (probability of necessity, Hannart et al. 2016 / Stott et al. 2004), `PR = P1/P0`.
  The event-level value averages P1 and P0 over the event days. A second variant uses the event's *observed peak magnitude* instead of the IMD criterion.
"""

class AttrNet(nn.Module):
    def __init__(s, H, W, n_day=4, n_loc=3, hid=64):
        super().__init__()
        s.conv = nn.Sequential(nn.Conv2d(1, 16, 3, padding=1), nn.ReLU(), nn.Conv2d(16, 32, 3, padding=1), nn.ReLU(), nn.AvgPool2d(2))
        s.fc = nn.Sequential(nn.Flatten(), nn.Linear(32 * (H // 2) * (W // 2), hid), nn.ReLU())
        s.head = nn.Sequential(nn.Linear(hid + n_day + n_loc, 64), nn.ReLU(), nn.Linear(64, 32), nn.ReLU(), nn.Linear(32, 1))
    def forward(s, x, d, loc):
        f = s.fc(s.conv(x)); B, Lc = f.shape[0], loc.shape[0]
        h = torch.cat([f[:, None, :].expand(B, Lc, -1), d[:, None, :].expand(B, Lc, -1), loc[None].expand(B, -1, -1)], -1)
        return s.head(h).squeeze(-1)

MAPS_T = torch.tensor(ZS[:, None], dtype=torch.float32)
lf = np.c_[LOC.lat.values, LOC.lon.values, NORM_S.max(0)]
LOCF = torch.tensor((lf - lf.mean(0)) / lf.std(0), dtype=torch.float32)
YS = 2.0
def day_scalars(days, Gv): return torch.tensor(np.c_[S1[days], C1[days], SW_S[days], (Gv - GBAR) / 0.4], dtype=torch.float32)
@torch.no_grad()
def predict_net(net, days, Gv):
    net.eval(); out = []
    for i in range(0, len(days), 512):
        d = days[i:i + 512]; out.append(net(MAPS_T[d], day_scalars(d, Gv[i:i + 512]), LOCF).numpy())
    return np.concatenate(out) * YS                     # degC anomaly, shape (n, L)

def train_member(days, loc_mask, seed, epochs=EPOCHS):
    torch.manual_seed(seed); net = AttrNet(H, W); opt = torch.optim.Adam(net.parameters(), lr=2e-3, weight_decay=1e-4)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
    X, dsc, Yt, lm = MAPS_T[days], day_scalars(days, G_S[days]), torch.tensor(Y_S[days] / YS, dtype=torch.float32), torch.tensor(loc_mask)
    n = len(days)
    for ep in range(epochs):
        net.train(); perm = torch.randperm(n)
        for i in range(0, n, 128):
            b = perm[i:i + 128]; loss = ((net(X[b], dsc[b], LOCF) - Yt[b])[:, lm] ** 2).mean()
            opt.zero_grad(); loss.backward(); opt.step()
        sch.step()
    return net

def train_ensemble(train_years, n, seed0, loc_mask=None, boot=True, sigma_years=None):
    loc_mask = np.ones(L, bool) if loc_mask is None else loc_mask
    rng = np.random.default_rng(seed0); members = []
    for k in range(n):
        yb = rng.choice(train_years, len(train_years)) if boot else np.array(train_years)
        while boot and len(np.setdiff1d(train_years, yb)) == 0:      # need >= 1 out-of-bag year to estimate sigma
            yb = rng.choice(train_years, len(train_years))
        sig_days = days_from_years(np.setdiff1d(train_years, yb)) if boot else days_from_years(sigma_years)
        net = train_member(days_from_years(yb), loc_mask, seed0 * 1000 + k)
        sigma = (Y_S[sig_days] - predict_net(net, sig_days, G_S[sig_days])).std(0)
        sigma[~loc_mask] = sigma[loc_mask].mean()
        members.append(dict(net=net, sigma=sigma, years=yb))
    return members
def ens_prob(ens, days, Gv):
    return np.mean([ndtr(-(MARGIN_S[days] - predict_net(m["net"], days, Gv)) / m["sigma"][None]) for m in ens], 0)
def ens_mu(ens, days, Gv): return np.mean([predict_net(m["net"], days, Gv) for m in ens], 0)

