def pack_cmip(cm):
    hist, nat = {}, {}
    for m in CMIP_MODELS:
        for store, exp in ((hist, "historical"), (nat, "hist-nat")):
            sub = cm[(cm.model == m) & (cm.experiment == exp)]
            if sub.empty: continue
            w = sub.pivot_table(index="year", columns="member", values="tas_K")
            baseline = w.loc[(w.index >= 1850) & (w.index <= 1900)].mean().mean()
            if pd.isna(baseline):
                print(f"Skipping {m} {exp}: no 1850-1900 baseline in CMIP6 data")
                continue
            store[m] = (w - baseline).reindex(YEARS)  # anomaly vs the model's own 1850-1900 mean
    return hist, nat

